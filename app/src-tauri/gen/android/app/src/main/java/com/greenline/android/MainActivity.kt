package com.greenline.android

import android.graphics.Color
import android.os.Bundle
import android.view.View
import androidx.activity.SystemBarStyle
import androidx.activity.enableEdgeToEdge
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat

class MainActivity : TauriActivity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    // Task 2bf.5: Android 15+ always draws apps edge to edge, so the WebView would sit under the
    // status bar, the camera cutout and the gesture bar. Pad the content view by those insets instead,
    // with the toolbar green behind the bars and light (white) bar icons. This does not depend on the
    // WebView's CSS env(safe-area-inset-*) values.
    enableEdgeToEdge(
      statusBarStyle = SystemBarStyle.dark(Color.TRANSPARENT),
      navigationBarStyle = SystemBarStyle.dark(Color.TRANSPARENT),
    )
    super.onCreate(savedInstanceState)
    window.decorView.setBackgroundColor(BAR_GREEN)
    val content = findViewById<View>(android.R.id.content)
    ViewCompat.setOnApplyWindowInsetsListener(content) { v, insets ->
      val b = insets.getInsets(WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.displayCutout())
      v.setPadding(b.left, b.top, b.right, b.bottom)
      WindowInsetsCompat.CONSUMED
    }
    ViewCompat.requestApplyInsets(content)
  }

  // Memory guard (task 2b.4): Android's memory callbacks and backgrounding tell the engine to drop its
  // display list and empty MuPDF's store. The call only sets an atomic in Rust and wakes the engine
  // thread (app/src-tauri/src/jni.rs); it does not go through the WebView and never blocks. No logging.
  // NOTE: this file is under gen/android (generated by `tauri android init`); re-running init
  // overwrites it, so these hooks must then be restored.

  // Task 2bf.2: only real pressure (level >= TRIM_MEMORY_BACKGROUND (40), or RUNNING_CRITICAL (15)) is
  // a hard trim. UI_HIDDEN (20) and the other running levels are light: the SAF picker fires them on
  // every open, and they must not abort a read.
  override fun onTrimMemory(level: Int) {
    super.onTrimMemory(level)
    trim(if (level >= 40 || level == 15) TRIM_MEMORY else LIGHT)
  }

  override fun onLowMemory() {
    super.onLowMemory()
    trim(LOW_MEMORY)
  }

  override fun onStop() {
    super.onStop()
    trim(BACKGROUND)
  }

  private fun trim(kind: Int) {
    try {
      nativeTrim(kind)
    } catch (e: UnsatisfiedLinkError) {
      // libapp_lib not loaded yet (no engine running either): nothing to release.
    }
  }

  private external fun nativeTrim(kind: Int)

  private companion object {
    const val BAR_GREEN = 0xFF1B5E20.toInt() // the viewer toolbar's green (#1b5e20)
    const val TRIM_MEMORY = 1
    const val LOW_MEMORY = 2
    const val BACKGROUND = 3
    const val LIGHT = 4
  }
}
